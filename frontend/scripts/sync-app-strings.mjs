// Copies the mobile app's English and Urdu texts (Flutter ARB files) into
// src/lib/i18n/app-strings.ts, so the website's account pages use the very
// same words as the app.
//
// Usage: node scripts/sync-app-strings.mjs <path to pakfix_app/lib/l10n>
// Re-run whenever the app's texts change, and commit the result.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = process.argv[2];
if (!dir) {
  console.error('Usage: node scripts/sync-app-strings.mjs <pakfix_app/lib/l10n>');
  process.exit(1);
}

const load = (file) => {
  const all = JSON.parse(readFileSync(join(dir, file), 'utf8'));
  return Object.fromEntries(Object.entries(all).filter(([k]) => !k.startsWith('@')));
};

const en = load('app_en.arb');
const ur = load('app_ur.arb');
const missing = Object.keys(en).filter((k) => !(k in ur));
if (missing.length) {
  console.error(`Urdu is missing ${missing.length} keys: ${missing.slice(0, 10).join(', ')}`);
  process.exit(1);
}

const sorted = (o) => Object.fromEntries(Object.keys(o).sort().map((k) => [k, o[k]]));
const out = `// GENERATED by scripts/sync-app-strings.mjs from the app's l10n files. Do not edit by hand.
// ${Object.keys(en).length} texts, English and Urdu.

export const APP_STRINGS_EN = ${JSON.stringify(sorted(en), null, 2)} as const;

export const APP_STRINGS_UR: Record<AppStringKey, string> = ${JSON.stringify(sorted(ur), null, 2)};

export type AppStringKey = keyof typeof APP_STRINGS_EN;
`;

const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'i18n', 'app-strings.ts');
writeFileSync(target, out);
console.log(`Wrote ${Object.keys(en).length} texts to ${target}`);
